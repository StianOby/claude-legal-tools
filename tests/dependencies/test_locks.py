#!/usr/bin/env python3
"""The pinned dependencies (CLAUDE.md, "Pinned dependencies"): every
plugins/*/skills/*/scripts/requirements.in has its lock beside it, compiled
by pip-compile, pinning every direct dependency with ==;
every script that runs pip passes the lock as constraints; and the bump
script used on Dependabot's PRs updates every copy of a version.
Run: python tests/dependencies/test_locks.py
"""

import importlib.util
import json
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
failures = 0


def check(name, got, want):
    global failures
    if got == want:
        print(f"  ok   {name}")
    else:
        print(f"  FAIL {name}: got {got!r}, want {want!r}")
        failures += 1


def names(text: str) -> set:
    out = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.add(re.split(r"[=<>!~ \[;]", line, maxsplit=1)[0].lower().replace("_", "-"))
    return out


print("lock files")
ins = sorted(ROOT.glob("plugins/*/skills/*/scripts/requirements.in"))
check("nbno and kildesjekk have one", sorted(p.parts[-3] for p in ins), ["kildesjekk", "nbno"])
for src in ins:
    plugin = src.parts[-3]
    lock = src.with_suffix(".txt")
    check(f"{plugin}: lock beside requirements.in", lock.exists(), True)
    text = lock.read_text(encoding="utf-8")
    # Not checked: the Python in pip-compile's header. Dependabot may
    # recompile on a newer Python; whether the pins install on 3.10 is what
    # matters, and validate.yml's "pinned" job tests exactly that.
    check(f"{plugin}: compiled by pip-compile", "autogenerated by pip-compile" in text, True)
    pinned = {n.lower(): v for n, v in re.findall(r"^([A-Za-z0-9._-]+)==(\S+)", text, re.M)}
    missing = sorted(n for n in names(src.read_text(encoding="utf-8")) if n not in pinned)
    check(f"{plugin}: every direct dependency pinned", missing, [])
    lines = [l for l in text.splitlines() if l and not l.lstrip().startswith("#")]
    check(f"{plugin}: nothing unpinned in the lock", [l for l in lines if "==" not in l], [])

print("every pip install in a plugin's scripts uses its lock")
for src in ins:
    scripts = src.parent
    for path in sorted(scripts.glob("*.py")) + sorted(scripts.glob("*.sh")):
        text = path.read_text(encoding="utf-8")
        if not re.search(r'"pip", "install"|\bpip install\b', text):
            continue
        check(f"{path.parent.parent.name}/{path.name}: refers to requirements.txt", "requirements.txt" in text, True)

print("bump script")
spec = importlib.util.spec_from_file_location("bump", ROOT / ".github" / "scripts" / "bump-plugin-versions.py")
bump = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bump)
check("patch", bump.bumped("1.5.9", "patch"), "1.5.10")
check("minor", bump.bumped("1.5.9", "minor"), "1.6.0")
with tempfile.TemporaryDirectory() as tmp:
    root = Path(tmp)
    plug = root / "plugins" / "demo"
    (plug / ".claude-plugin").mkdir(parents=True)
    (plug / ".claude-plugin" / "plugin.json").write_text('{\n  "name": "demo",\n  "version": "0.4.2"\n}\n')
    scripts = plug / "skills" / "demo" / "scripts"
    (scripts / "browser").mkdir(parents=True)
    (scripts / "a.py").write_text('VERSION = "0.4.2"\nUA = "demo-skill/0.4.2 (+x)"\n# 2 (0.4.2): history\nOTHER = "0.4.2"\n')
    (scripts / "browser" / "demo.js").write_text("const HELPER_VERSION = '0.4.2';\n")
    bump.ROOT = root
    check("returns the new version", bump.bump("demo", "patch", None), "0.4.3")
    check("plugin.json", json.loads((plug / ".claude-plugin" / "plugin.json").read_text())["version"], "0.4.3")
    check("VERSION and UA updated, comment and other strings kept", (scripts / "a.py").read_text(),
          'VERSION = "0.4.3"\nUA = "demo-skill/0.4.3 (+x)"\n# 2 (0.4.2): history\nOTHER = "0.4.2"\n')
    check("an unchanged browser helper keeps its version", (scripts / "browser" / "demo.js").read_text(),
          "const HELPER_VERSION = '0.4.2';\n")

print(f"{failures} failure(s)" if failures else "all ok")
sys.exit(1 if failures else 0)
